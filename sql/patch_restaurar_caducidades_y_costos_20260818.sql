-- 0) Diagnóstico (se imprime en Notices / Results)
do $diag$
declare
  n_lotes int; n_cad int; n_sin_cad int; n_prod int; n_stock_sin_lote int;
begin
  select count(*) into n_prod from public.productos where coalesce(activo,true);
  select count(*) into n_lotes from public.lotes where coalesce(activo,true);
  select count(*) into n_cad from public.lotes where coalesce(activo,true) and fecha_caducidad is not null;
  select count(*) into n_sin_cad from public.lotes where coalesce(activo,true) and cantidad_actual > 0 and fecha_caducidad is null;
  select count(*) into n_stock_sin_lote
    from public.productos p
    where coalesce(p.activo,true) and coalesce(p.stock,0) > 0
      and not exists (select 1 from public.lotes l where l.producto_id = p.id and coalesce(l.activo,true) and l.cantidad_actual > 0);
  raise notice 'productos activos=%  lotes activos=%  lotes con caducidad=%  lotes stock sin fecha=%  stock sin lote=%',
    n_prod, n_lotes, n_cad, n_sin_cad, n_stock_sin_lote;
end $diag$;

