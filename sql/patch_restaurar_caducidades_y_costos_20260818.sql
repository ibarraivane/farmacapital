select p.id,
       'SIN-LOTE-' || coalesce(nullif(btrim(p.sku), ''), p.id::text),
       greatest(p.stock, 0)::integer,
       greatest(p.stock, 0)::integer,
       coalesce(p.costo, 0),
       null::date,
       coalesce(p.created_at::date, current_date),
       true
from public.productos p
where coalesce(p.activo, true)
  and coalesce(p.stock, 0) > 0
  and not exists (
    select 1 from public.lotes l
    where l.producto_id = p.id and coalesce(l.activo, true) and coalesce(l.cantidad_actual, 0) > 0
